const tashkeelPattern = new RegExp(
  Object.keys(tashkeel).sort((a, b) => b.length - a.length).map((word) => word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'),
  'gu',
)

function addTashkeel(text: string) {
  return text.replace(tashkeelPattern, (word) => tashkeel[word] ?? word)
}

export function canSpeak() {
  return typeof window !== 'undefined' && 'speechSynthesis' in window
}

export function speak(text: string, onEnd?: () => void) {
  if (!canSpeak()) return
  window.speechSynthesis.cancel()
  const u = new SpeechSynthesisUtterance(addTashkeel(text))
  u.lang = 'ar-SA'
  u.rate = 0.88
  u.pitch = 1.05
  const voice = window.speechSynthesis.getVoices().find((v) => v.lang.startsWith('ar'))
  if (voice) u.voice = voice
  if (onEnd) u.onend = onEnd
  window.speechSynthesis.speak(u)
}

export function stopSpeaking() {
  if (canSpeak()) window.speechSynthesis.cancel()
}
